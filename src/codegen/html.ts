export interface CssOptions {
  /** URL of a bundled font file, by file name. */
  fontUrl: (file: string) => string;
}

/** Shared base styles: a small reset that makes elements start from the canvas's blank slate, and fonts. */
export function baseCss(fonts: readonly string[], usesContents: boolean, options: CssOptions): string {
  const parts = [
    '/* Base styles for pages generated by StyleCode. */',
    '',
    '*,',
    '*::before,',
    '*::after {',
    '  box-sizing: border-box;',
    '}',
    '',
    'body,',
    'h1,',
    'h2,',
    'h3,',
    'h4,',
    'h5,',
    'h6,',
    'p,',
    'ul {',
    '  margin: 0;',
    '}',
    '',
    'ul {',
    '  padding: 0;',
    '  list-style: none;',
    '}',
    '',
    'img {',
    '  display: block;',
    '}',
    '',
    'button,',
    'input {',
    '  margin: 0;',
    '  padding: 0;',
    '  border: 0;',
    '  background: none;',
    '  font: inherit;',
    '  color: inherit;',
    '  text-align: inherit;',
    '}',
    '',
    'button {',
    '  cursor: pointer;',
    '}',
    '',
    'a {',
    '  color: inherit;',
    '  text-decoration: none;',
    '}',
  ];
  if (usesContents)
    parts.push(
      '',
      '/* List items that leave layout to the element inside them. */',
      '.display-contents {',
      '  display: contents;',
      '}',
    );
  for (const font of fontFilesFor(fonts)) {
    parts.push(
      '',
      '@font-face {',
      `  font-family: '${font.family}';`,
      '  font-style: normal;',
      `  font-weight: ${font.weight};`,
      '  font-display: swap;',
      `  src: url('${options.fontUrl(font.file)}') format('woff2');`,
      `  unicode-range: ${font.unicodeRange};`,
      '}',
    );
  }
  return `${parts.join('\n')}\n`;
}

export function usesDisplayContents(element: ElementNode): boolean {
  return element.className === 'display-contents' || element.children.some(usesDisplayContents);
}

/** Text safe inside a CSS comment: it can't end the comment early. */
function commentText(text: string): string {
  return text.replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ');
}

function printRule(p: Printer, rule: Rule, indent: string, selector: (rule: Rule) => string): void {
  if (rule.comment) p.push(`${indent}/* ${commentText(rule.comment)} */`);
  const start = p.line;
  p.push(`${indent}${selector(rule)} {`);
  for (const d of rule.decls) p.push(`${indent}  ${d.prop}: ${d.value};`);
  p.push(`${indent}}`);
  p.mark(rule.nodeId, start, p.line - 1);
}

/** The rule text for one layer's base rule: what the code panel lets you edit. */
export function declarationsText(decls: readonly Decl[]): string {
  return decls.map((d) => `${d.prop}: ${d.value};`).join('\n');
}

/** The stylesheet for one screen. `selector` lets the React printer use the same rules. */
export function screenCss(screen: Screen, selector: (rule: Rule) => string = defaultSelector, bodySelector = 'body'): Printed {
  const p = new Printer();
  p.push(
    `/* ${commentText(screen.name || 'Screen')}: generated by StyleCode from a ${Math.round(screen.width)}px-wide design. */`,
  );
  const background = screen.rules.find((r) => r.nodeId === screen.id && !r.pseudo)?.decls.find((d) => d.prop === 'background');
  if (background) {
    p.push('');
    const start = p.line;
    p.push(`${bodySelector} {`, `  background: ${background.value};`, '}');
    p.mark(screen.id, start, p.line - 1);
  }
  for (const rule of screen.rules) {
    p.push('');
    printRule(p, rule, '', selector);
  }
  if (screen.responsive.length) {
    const below = Math.max(0, Math.round(screen.width) - 1);
    p.push(
      '',
      `/* Below ${Math.round(screen.width)}px: rows wrap, fixed widths shrink, and large text and spacing scale down. */`,
    );
    p.push(`@media (max-width: ${below}px) {`);
    screen.responsive.forEach((rule, i) => {
      if (i) p.push('');
      printRule(p, rule, '  ', selector);
    });
    p.push('}');
  }
  return p.done();
}

function defaultSelector(rule: Rule): string {
  return `.${rule.className}${rule.pseudo ?? ''}`;
}

// ---------------------------------------------------------------------------
// HTML
// ---------------------------------------------------------------------------

export interface HtmlOptions {
  /** URL for an image asset. */
  imageUrl: (asset: string) => string;
  /** Stylesheets to link, or inline CSS to embed instead (for the preview). */
  stylesheets?: string[];
  inlineCss?: string;
}

function printElement(p: Printer, el: ElementNode, indent: string, options: HtmlOptions): void {
  const attrs = [`class="${escapeAttr(el.className)}"`];
  for (const [name, value] of el.attrs) attrs.push(`${name}="${escapeAttr(value)}"`);
  if (el.asset) attrs.splice(1, 0, `src="${escapeAttr(options.imageUrl(el.asset))}"`);
  const open = `<${el.tag} ${attrs.join(' ')}>`;
  const start = p.line;
  if (el.tag === 'img' || el.tag === 'input') {
    p.push(`${indent}${open}`);
  } else if (el.text !== undefined) {
    // On one line: whitespace inside text elements is significant.
    p.push(`${indent}${open}${escapeText(el.text)}</${el.tag}>`);
  } else if (el.children.length === 0) {
    p.push(`${indent}${open}</${el.tag}>`);
  } else {
    p.push(`${indent}${open}`);
    for (const child of el.children) printElement(p, child, `${indent}  `, options);
    p.push(`${indent}</${el.tag}>`);
  }
  p.mark(el.id, start, p.line - 1);
}

/** A complete HTML page for one screen. */
export function screenHtml(screen: Screen, options: HtmlOptions): Printed {
  const p = new Printer();
  p.push('<!doctype html>', '<html lang="en">', '  <head>');
  p.push('    <meta charset="utf-8">', '    <meta name="viewport" content="width=device-width, initial-scale=1">');
  p.push(`    <title>${escapeText(screen.name || 'Screen')}</title>`);
  for (const href of options.stylesheets ?? []) p.push(`    <link rel="stylesheet" href="${escapeAttr(href)}">`);
  if (options.inlineCss !== undefined) {
    p.push(
      '    <style>',
      ...options.inlineCss
        .replace(/<\/style/gi, '<\\/style')
        .trimEnd()
        .split('\n'),
      '    </style>',
    );
  }
  p.push('  </head>', '  <body>');
  printElement(p, screen.root, '    ', options);
  p.push('  </body>', '</html>');
  return p.done();
}
