import { fontFilesFor } from './fonts';
import type { Decl, ElementNode, Rule, Screen } from './screen';

/**
 * Printing a screen as an HTML page and its stylesheet. Every printed file
 * comes with a line map (which lines belong to which layer), so the code
 * panel can highlight the selected layer's code.
 */

/** Line ranges (1-based, inclusive) per layer id. */
export type LineMap = Map<string, [number, number][]>;

export interface Printed {
  content: string;
  lines: LineMap;
}

class Printer {
  private readonly out: string[] = [];
  readonly lines: LineMap = new Map();

  get line(): number {
    return this.out.length + 1;
  }

  push(...lines: string[]): void {
    // Text may hold line breaks; count them so line numbers stay right.
    for (const line of lines) this.out.push(...line.split('\n'));
  }

  mark(id: string, from: number, to: number): void {
    if (!id) return;
    const ranges = this.lines.get(id) ?? [];
    ranges.push([from, to]);
    this.lines.set(id, ranges);
  }

  done(): Printed {
    return { content: `${this.out.join('\n')}\n`, lines: this.lines };
  }
}

export function escapeText(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function escapeAttr(text: string): string {
  return escapeText(text).replace(/"/g, '&quot;');
}

